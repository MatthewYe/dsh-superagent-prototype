"""Command line entry point for the ontology-gate experiment."""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

from .gate import GateError, check, find_binary, frontier
from .scenarios import (
    PROJECT_ROOT,
    SHAPES,
    TBOX,
    run_all,
    save_results,
)

DEFAULT_WORKDIR = PROJECT_ROOT / ".runs"
RESULTS_PATH = PROJECT_ROOT / "RESULTS.md"


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _first_message(result) -> str:
    messages = result.gate.messages()
    return messages[0].replace("|", "\\|") if messages else ""


def write_results_markdown(results, path: Path, binary: Path) -> None:
    passed = sum(1 for result in results if result.passed)
    stamp = datetime.now(timezone.utc).isoformat(timespec="seconds")
    try:
        display_binary = binary.relative_to(PROJECT_ROOT)
    except ValueError:
        display_binary = binary
    lines = [
        "# Ontology gate MVP — measured results",
        "",
        f"Generated by `python3 -m ontology_gate demo` at {stamp}.",
        "",
        "- open-ontologies release: **v2.1.0** (pinned by `scripts/fetch-open-ontologies.sh`)",
        f"- binary: `{display_binary}`",
        f"- binary sha256: `{_sha256(binary)}`",
        (
            f"- scenarios whose real exit code and messages matched the expectation: "
            f"**{passed}/{len(results)}**"
        ),
        "",
        "The gate is the standalone `open-ontologies shacl` command. Each row below",
        "built a real git repository, ran the configured lint and unittest commands,",
        "made real commits, then loaded the generated Turtle plus `ontology/tickets.ttl`",
        "and `ontology/shapes.ttl` into a fresh persistent store.",
        "",
        "| scenario | expected exit | actual exit | verdict | first violation |",
        "|---|---:|---:|---|---|",
    ]
    for result in results:
        verdict = "PASS" if result.passed else "FAIL"
        lines.append(
            f"| `{result.scenario.name}` | {result.scenario.expected_exit} | "
            f"{result.gate.exit_code} | {verdict} | {_first_message(result)} |"
        )
        if result.failures:
            lines.append(f"| | | | | unexpected: {'; '.join(result.failures)} |")
    lines += [
        "",
        "## What the results show",
        "",
        "- Ticket dependency order and completion constraints are enforced by SHACL",
        "  shapes, and a violation produces a nonzero `shacl` exit code. The gate does",
        "  not need to parse the JSON to block; the process exit code is enough.",
        "- A false `Done` claim is rejected both at ticket level (missing or failing",
        "  evidence, dirty tree, stale commit) and at spec level (any unfinished",
        "  ticket, or a completed spec with no tickets).",
        "- Two independent traps were measured on v2.1.0: `batch` exits 0 even when",
        "  `shacl` prints `conforms:false`, and `reason --profile owl-dl` exits 0 on an",
        "  inconsistent ontology. Neither can be used as a gate without parsing JSON.",
        "- Any SHACL constraint the evaluator cannot compile makes `shacl` exit 2 with",
        "  `conforms:null`; the wrapper records `skipped_constraints` as warnings so",
        "  an indeterminate verdict cannot silently pass.",
        "",
        "## What this does not prove",
        "",
        "- The ontology checks *claims*, not reality. This experiment runs the",
        "  commands in a collector first, so the recorded facts are real. A caller",
        "  that fabricates a conforming Turtle file would pass; keeping the collector",
        "  inside the trusted boundary (or re-running it at gate time) is essential.",
        "- OWL reasoning is informative here, not a gate: the measured `reason`",
        "  command returned `consistent:false` with exit code 0.",
        "- Only the v2.1.0 macOS arm64 binary was exercised. The fetch script pins",
        "  the published checksums for macOS arm64/x86_64 and Linux x86_64.",
        "",
        "Per-scenario Turtle and the raw violation JSON are kept under `.runs/`",
        "when the demo runs.",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


def cmd_demo(args: argparse.Namespace) -> int:
    workdir = Path(args.workdir).resolve()
    binary = find_binary()
    print(f"using open-ontologies: {binary}")
    results = run_all(workdir)
    save_results(results, workdir)
    write_results_markdown(results, Path(args.results_md), binary)

    for result in results:
        status = "PASS" if result.passed else "FAIL"
        print(
            f"{status:4}  {result.scenario.name:26} "
            f"exit={result.gate.exit_code} expected={result.scenario.expected_exit}"
        )
        for failure in result.failures:
            print(f"      {failure}")
        if result.gate.warnings:
            for warning in result.gate.warnings:
                print(f"      warning: {warning}")

    passed = sum(1 for result in results if result.passed)
    print(f"\n{passed}/{len(results)} scenarios matched expectations")
    print(f"wrote {Path(args.results_md)}")
    return 0 if passed == len(results) else 1


def cmd_check(args: argparse.Namespace) -> int:
    state = Path(args.state)
    result = check(
        state.read_text(encoding="utf-8"),
        Path(args.tbox),
        Path(args.shapes),
    )
    if args.json:
        print(json.dumps(result.to_dict(), indent=2))
    else:
        print(
            f"exit={result.exit_code} conforms={result.conforms} "
            f"focus_nodes={result.focus_nodes}"
        )
        for message in result.messages():
            print(f"violation: {message}")
        for warning in result.warnings:
            print(f"warning: {warning}")
    return result.exit_code if result.exit_code in (0, 1) else 2


def cmd_frontier(args: argparse.Namespace) -> int:
    state = Path(args.state).read_text(encoding="utf-8")
    ready = frontier(state, Path(args.tbox), args.spec)
    print(json.dumps(ready, indent=2))
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="ontology_gate")
    subparsers = parser.add_subparsers(dest="command", required=True)

    demo = subparsers.add_parser(
        "demo", help="run every scenario against a real binary and write RESULTS.md"
    )
    demo.add_argument("--workdir", default=str(DEFAULT_WORKDIR))
    demo.add_argument("--results-md", default=str(RESULTS_PATH))
    demo.set_defaults(func=cmd_demo)

    check_parser = subparsers.add_parser(
        "check", help="gate an existing Turtle state file"
    )
    check_parser.add_argument("--state", required=True)
    check_parser.add_argument("--tbox", default=str(TBOX))
    check_parser.add_argument("--shapes", default=str(SHAPES))
    check_parser.add_argument("--json", action="store_true")
    check_parser.set_defaults(func=cmd_check)

    frontier_parser = subparsers.add_parser(
        "frontier", help="list ready Todo tickets from an existing state file"
    )
    frontier_parser.add_argument("--state", required=True)
    frontier_parser.add_argument("--spec", required=True)
    frontier_parser.add_argument("--tbox", default=str(TBOX))
    frontier_parser.set_defaults(func=cmd_frontier)
    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    try:
        return args.func(args)
    except GateError as error:
        print(f"gate error: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
